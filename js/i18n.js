  const phrasePattern = new RegExp(keys.filter(key => key.length > 1).map(escape).join('|'), 'g');
  let language = localStorage.getItem('iryu_language') === 'zh-TW' ? 'zh-TW' : 'ko';
  const textRecords = new WeakMap();
  const attributeRecords = new WeakMap();
  const attributes = ['placeholder', 'title', 'aria-label', 'alt'];
  let observer;

  function translate(value) {
    if (language !== 'zh-TW' || !/[가-힣]/.test(value)) return value;
    // 긴 문장/게임 용어를 먼저 치환하고 숫자 단위는 숫자 옆에서만 치환한다.
    return value.replace(/(\d[\d,.]*)\s*시간/g, '$1小時')
      .replace(phrasePattern, match => dictionary[match])
      .replace(/([0-9,.\s])([만억조경해자양구간정재극개회장분초일층배])/g,
        (_, number, unit) => number + (dictionary[unit] || unit))
      .replace(/[가-힣]+/g, word => Object.prototype.hasOwnProperty.call(dictionary, word) ? dictionary[word] : word)
      .replace(/([\u3400-\u9fff]) +(?=[\u3400-\u9fff])/g, '$1');
  }

  function excluded(element) {
    return !element || !!element.closest('script, style, textarea, [contenteditable], [translate="no"], .notranslate');
  }

  function updateText(node) {
    if (excluded(node.parentElement)) return;
    let record = textRecords.get(node);
    if (!record || node.nodeValue !== record.last) {
      record = { source: node.nodeValue, last: node.nodeValue };
      textRecords.set(node, record);
    }
    // value 생략 옵션은 표시 문구 변경으로 계산용 값이 바뀌지 않도록 고정한다.
    const parent = node.parentElement;
    if (parent.tagName === 'OPTION' && !parent.hasAttribute('value')) parent.setAttribute('value', parent.value);
    const next = translate(record.source);
    record.last = next;
    if (node.nodeValue !== next) node.nodeValue = next;
  }

  function updateAttributes(element) {
    if (excluded(element)) return;
    let records = attributeRecords.get(element);
    if (!records) { records = {}; attributeRecords.set(element, records); }
    for (const name of attributes) {
      const current = element.getAttribute(name);
      if (current === null) { delete records[name]; continue; }
      let record = records[name];
      if (!record || current !== record.last) record = records[name] = { source: current, last: current };
      const next = translate(record.source);
      record.last = next;
      if (current !== next) element.setAttribute(name, next);
    }
  }

  function updateTree(root) {
    if (root.nodeType === Node.TEXT_NODE) { updateText(root); return; }
    if (root.nodeType !== Node.ELEMENT_NODE && root.nodeType !== Node.DOCUMENT_NODE) return;
    if (root.nodeType === Node.ELEMENT_NODE) updateAttributes(root);
    const walker = document.createTreeWalker(root, NodeFilter.SHOW_ELEMENT | NodeFilter.SHOW_TEXT);
    let node;
    while ((node = walker.nextNode())) {
      if (node.nodeType === Node.TEXT_NODE) updateText(node);
      else updateAttributes(node);
    }
  }

  function processChanges(changes) {
    for (const change of changes) {
      if (change.type === 'childList') change.addedNodes.forEach(updateTree);
      else if (change.type === 'characterData') updateText(change.target);
      else updateAttributes(change.target);
    }
  }

  function updateButton() {
    const button = document.getElementById('languageToggle');
    if (!button) return;
    button.textContent = language === 'ko' ? '繁體中文' : '한국어';
    button.lang = language === 'ko' ? 'zh-TW' : 'ko';
    button.setAttribute('aria-label', language === 'ko' ? '대만 번체 중국어로 번역' : '切換為韓文');
    button.setAttribute('aria-pressed', String(language === 'zh-TW'));
  }

  function setLanguage(next) {
    // 외부 코드가 방금 변경한 한국어도 원본으로 기록한 뒤 언어를 바꾼다.
    if (observer) processChanges(observer.takeRecords());
    language = next === 'zh-TW' ? 'zh-TW' : 'ko';
    localStorage.setItem('iryu_language', language);
    document.documentElement.lang = language;
    updateTree(document.documentElement);
    updateButton();
    document.dispatchEvent(new CustomEvent('iryu:languagechange', { detail: { language } }));
  }

  window.iryuI18n = { translate, setLanguage, getLanguage: () => language };
  for (const name of ['alert', 'confirm', 'prompt']) {
    const original = window[name].bind(window);
    window[name] = (message, ...args) => original(translate(String(message)), ...args);
  }

  function initialize() {
    document.documentElement.lang = language;
    updateTree(document.documentElement);
    updateButton();
    document.addEventListener('click', event => {
      if (event.target.closest('#languageToggle')) setLanguage(language === 'ko' ? 'zh-TW' : 'ko');
    });
    window.addEventListener('storage', event => {
      if (event.key === 'iryu_language') setLanguage(event.newValue);
    });
    observer = new MutationObserver(processChanges);
    observer.observe(document.documentElement, { subtree: true, childList: true, characterData: true,
      attributes: true, attributeFilter: attributes });
  }
  if (document.readyState === 'loading') document.addEventListener('DOMContentLoaded', initialize);
  else initialize();
