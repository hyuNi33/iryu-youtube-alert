  const languages = ['ko', 'zh-TW', 'en'];
  const patterns = {};
  const escape = value => value.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
  for (const [code, dictionary] of Object.entries(dictionaries)) {
    patterns[code] = new RegExp(Object.keys(dictionary).filter(key => key.length > 1)
      .sort((a,b) => b.length-a.length).map(escape).join('|'), 'g');
  }
  const savedLanguage = localStorage.getItem('iryu_language');
